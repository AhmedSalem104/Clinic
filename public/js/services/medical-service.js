import { api } from '../core/api-service.js';
export const medicalService = {
  cases: (patientId) => api.get(`/cases?patientId=${patientId}`),
  createCase: (data) => api.post('/cases', data),
  visits: (params) => api.get(`/visits?${new URLSearchParams(params)}`),
  visit: (id) => api.get(`/visits/${id}`),
  createVisit: (data) => api.post('/visits', data),
  completeVisit: (id) => api.post(`/visits/${id}/complete`, {}),
  pregnancies: (patientId) => api.get(`/pregnancies?patientId=${patientId}`),
  createPregnancy: (data) => api.post('/pregnancies', data),
  medication: (patientId) => api.get(`/medications?patientId=${patientId}`),
  createMedication: (data) => api.post('/medications', data),
  medicationStatus: (id, data) => api.patch(`/medications/${id}/status`, data),
  allergies: (patientId) => api.get(`/allergies?patientId=${patientId}`),
  createAllergy: (data) => api.post('/allergies', data),
  labs: (patientId) => api.get(`/labs?patientId=${patientId}`),
  createLab: (data) => api.post('/labs', data),
  ultrasounds: (patientId) => api.get(`/ultrasounds?patientId=${patientId}`),
  createUltrasound: (data) => api.post('/ultrasounds', data),
  documents: (patientId) => api.get(`/documents?patientId=${patientId}`),
  uploadDocument: (formData) => api.upload('/documents', formData),
  progress: (patientId, indicator) => api.get(`/progress?patientId=${patientId}${indicator ? `&indicator=${encodeURIComponent(indicator)}` : ''}`),
  createProgress: (data) => api.post('/progress', data),
  gyneHistory: (patientId) => api.get(`/medical-history/gynecologic?patientId=${patientId}`),
  saveGyneHistory: (data) => api.put('/medical-history/gynecologic', data),
  obstetricHistory: (patientId) => api.get(`/medical-history/obstetric?patientId=${patientId}`),
  createObstetricHistory: (data) => api.post('/medical-history/obstetric', data),
  report: (patientId) => api.get(`/reports/patients/${patientId}/summary`)
};
